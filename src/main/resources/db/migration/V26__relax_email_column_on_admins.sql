-- admins.email 제거의 "확장(expand)" 단계. 컬럼은 남기고 NOT NULL 만 푼다.
--
-- 컬럼을 여기서 지우지 않는 이유:
-- 블루-그린 배포에서 Flyway 는 새 색 컨테이너가 부팅할 때 실행되는데, 그 시점에
-- 구 색 컨테이너가 아직 살아서 같은 DB 를 쓰고 있다. 트래픽 전환 후에도
-- DRAIN_SECONDS(기본 30초) 동안 구 버전이 요청을 계속 처리한다. 즉 마이그레이션
-- 직후 30초 이상 "구 코드 + 신 스키마" 상태가 지속된다.
-- 여기서 컬럼을 지우면 그 구간 동안 구 버전의 Admin 조회가 전부 실패한다.
-- 헬스체크는 스키마를 건드리지 않아 통과하므로, 배포는 "성공" 으로 보고된다.
--
-- 이 단계에서는 구/신 버전이 동시에 정상 동작한다:
--   구 코드 - email 을 읽고 쓴다. 컬럼이 그대로 있으므로 문제없다
--   신 코드 - email 을 매핑하지 않는다. NOT NULL 이 풀려 INSERT 가 통과한다
--
-- 실제 컬럼 삭제(수축, contract)는 email 을 참조하는 코드가 완전히 사라진
-- 다음 릴리스에서 V27 로 수행한다. (이슈 #405)
--
-- UNIQUE(uk_admins_email)은 유지한다. PostgreSQL 은 NULL 을 서로 다른 값으로
-- 취급하므로, email 없는 관리자가 여럿 생겨도 제약에 걸리지 않는다.
ALTER TABLE admins
    ALTER COLUMN email DROP NOT NULL;
